function inScope(node) {
  const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
  if (!element) return false;
  if (element.closest("[data-no-i18n]")) return false;
  return ROOTS.some((selector) => element.closest(selector));
}

function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (!inScope(node)) return;
    const next = t(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  if (["SCRIPT", "STYLE", "TEXTAREA"].includes(node.tagName)) return;
  if (node.closest("[data-no-i18n]")) return;
  for (const attribute of ["title", "placeholder", "aria-label"]) {
    const value = node.getAttribute(attribute);
    if (!value) continue;
    const next = t(value);
    if (next !== value) node.setAttribute(attribute, next);
  }
  for (const child of node.childNodes) translateNode(child);
}

function translateTree(root) {
  if (!root) return;
  translateNode(root);
}

export function initI18n() {
  window.__fx = window.__fx || {};
  window.__fx.t = t;
  window.__fx.isZh = isZh;
  if (!isZh()) return;
  const start = () => {
    translateTree(document.body);
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData") {
          translateNode(mutation.target);
        } else if (mutation.type === "attributes") {
          translateNode(mutation.target);
        } else {
          for (const node of mutation.addedNodes) translateNode(node);
        }
      }
    });
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["title", "placeholder", "aria-label"],
    });
  };
  if (document.body) start();
  else document.addEventListener("DOMContentLoaded", start, { once: true });
}
