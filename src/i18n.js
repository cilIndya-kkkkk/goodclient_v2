function normalize(text) {
  return String(text).replace(/\s+/g, " ").trim();
}

export function isZh() {
  const langParam = new URLSearchParams(location.search).get("lang");
  if (langParam) return /^zh/i.test(langParam);
  const saved = localStorage.getItem("fx_ui_language");
  if (saved === "zh") return true;
  if (saved === "en") return false;
  const configured = window.__fx && window.__fx.settings && window.__fx.settings.uiLanguage;
  if (configured === "zh") return true;
  if (configured === "en") return false;
  if (configured === "auto") return /^zh/i.test(navigator.language || "");
  return false;
}

export function t(text) {
  if (!isZh() || text === undefined || text === null) return text;
  const original = String(text);
  const leading = original.match(/^\s*/)[0];
  const trailing = original.match(/\s*$/)[0];
  const core = original.trim();
  if (!core) return original;
  const direct = ZH[core] ?? ZH[normalize(core)];
  if (direct !== undefined) return leading + direct + trailing;
  for (const [pattern, build] of PATTERNS) {
    const match = normalize(core).match(pattern);
    if (match) return leading + build(match) + trailing;
  }
  return original;
}

